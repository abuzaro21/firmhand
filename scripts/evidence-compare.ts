// Writes docs/evidence/comparisons.json and a markdown table: managed vs naive for both scenarios, all five test seeds.
import { writeFileSync } from 'node:fs';
import { compare } from '../src/compare.ts';

const SEEDS = [7, 11, 23, 42, 101];
const out: any[] = [];
const rows: string[] = [];
const $ = (c: number) => `$${(c / 100).toLocaleString('en-US', { maximumFractionDigits: 0 })}`;
for (const k of ['inventory-shock', 'operations-failure'] as const) {
  rows.push(`\n### ${k}\n`, '| Seed | Policy | Revenue | Net income | Shipped | Backlog | Late vs first promise | Re-promised | Lost | At risk | Expedite | Human decisions | Alert hour | Ops at end | Books reconcile |', '|---|---|---:|---:|---:|---:|---:|---:|---:|---:|---:|---:|---:|---|---|');
  for (const seed of SEEDS) {
    const r = await compare(k, seed);
    out.push({ kind: k, seed, assumption: r.assumption, managed: { ...r.managed, series: undefined }, naive: { ...r.naive, series: undefined } });
    for (const [label, x] of [['FIRMHAND', r.managed], ['naive', r.naive]] as const) {
      rows.push(`| ${seed} | ${label} | ${$(x.recognizedRevenue)} | ${$(x.netIncome)} | ${x.fulfilled} | ${x.backlogOrders} | ${x.lateVsOriginal} | ${x.renegotiated} | ${x.customersChurned} | ${x.customersAtRisk} | ${$(x.expediteSpend)} | ${x.humanDecisions} | ${x.firstAlertTick ?? '—'} | ${x.operationsEndStatus} | ${x.reconciliationOk ? 'yes' : 'NO'} |`);
    }
  }
}
writeFileSync('docs/evidence/comparisons.json', JSON.stringify(out, null, 2) + '\n');
writeFileSync('docs/evidence/comparisons.md', `# Managed vs naive, all test seeds\n\nGenerated by \`node scripts/evidence-compare.ts\`. Isolated in-memory companies, same seed and same injected event; only the policies differ. Assumption: ${out[0].assumption}\n${rows.join('\n')}\n`);
console.log(rows.join('\n'));
